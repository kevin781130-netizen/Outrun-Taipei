'use strict';
const assert=require('node:assert/strict');
const {SCHEMA,createFrameProbe}=require('../src/diagnostics/FrameProbe.cjs');
assert.equal(SCHEMA,'taipei.v64.frame-diagnostics.1');
const p=createFrameProbe({capacity:30,maxEvents:3,jankMs:50});
assert.equal(p.snapshot().framesPerSecond,null);
assert.equal(p.record({timestampMs:0,route:'1A'}),false);
for(let i=1;i<=50;i++)p.record({timestampMs:i*16.67,steps:1,updateMs:2,renderMs:4,route:'1A',heapBytes:4000000+i});
const s=p.snapshot({quality:'HIGH',route:'1A',viewportWidth:390,viewportHeight:844,ua:'SECRET',url:'SECRET'});
assert.equal(s.schema,SCHEMA);
assert.equal(s.sampleCount,30);
assert.equal(s.totalFrames,50);
assert.equal(s.totalSteps,50);
assert(s.framesPerSecond>59&&s.framesPerSecond<61);
assert.equal(s.frameP95Ms,16.67);
assert.equal(s.jsHeapBytes,4000050);
assert.equal(s.route,'1A');
assert(!JSON.stringify(s).includes('SECRET'),'privacy: no user agent or URL');
const unchanged=JSON.stringify(s);
const second=p.snapshot({quality:'HIGH',route:'1A',viewportWidth:390,viewportHeight:844});
assert.equal(JSON.stringify(second),unchanged,'deterministic bounded snapshot');
p.record({timestampMs:900,route:'1B',updateMs:20,renderMs:5,steps:4});
p.record({timestampMs:1000,route:'1B',updateMs:1,renderMs:5});
p.record({timestampMs:1100,route:'1B',updateMs:1,renderMs:5});
p.record({timestampMs:1200,route:'1B',updateMs:1,renderMs:5});
assert.equal(p.snapshot().retainedJankEvents.length,3,'bounded anomaly ring');
assert(p.snapshot().retainedJankEvents.every(e=>e.reason==='frame-gap'));
p.record({timestampMs:5000,paused:true});
p.record({timestampMs:6500,route:'2A'}); // resume establishes new clock
p.record({timestampMs:6516.7,route:'2A'});
assert.equal(p.snapshot().hiddenOrPausedFrames,1);
assert(p.snapshot().frameMaxMs<1500,'pauses excluded from frame gaps');
p.reset();assert.equal(p.snapshot().sampleCount,0);
assert.equal(p.snapshot().totalFrames,0);
const invalid=createFrameProbe();
invalid.record({timestampMs:0});
invalid.record({timestampMs:16.7,route:'http://secret',heapBytes:-1});
assert.equal(invalid.snapshot({route:'HIDDEN',viewportWidth:-1}).route,undefined);
assert.equal(invalid.snapshot().jsHeapBytes,null);
assert.throws(()=>createFrameProbe({capacity:4000}),RangeError);
assert.throws(()=>createFrameProbe({jankMs:0}),RangeError);
console.log('V64 diagnostics pure probe: bounded samples/events, FPS/p95, pause gap exclusion, reset and privacy checks passed');
