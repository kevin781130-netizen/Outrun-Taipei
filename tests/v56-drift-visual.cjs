'use strict';
const assert=require('node:assert/strict');
const {createDrivingVisualSnapshot,updateDrivingVisualSnapshot}=require('../src/rendering/DrivingVisualSnapshot.cjs');
const {createDriftVisualRig,updateDriftVisualRig,resetDriftVisualRig}=require('../src/rendering/DriftVisualRig.cjs');
const src={...createDrivingVisualSnapshot(),driftState:'entry',isDrifting:true,driftAngleDeg:24,slipAngleDeg:13,driftDirection:1,lateralVelocity:.4,roadGrip:.94,cleanDriftTime:.7,exitBoost:.3,momentBoostWindow:.4,driftCharge:53,nitroActive:true,yawDeg:31};
const before=JSON.stringify(src),snapshot=createDrivingVisualSnapshot();
assert.equal(updateDrivingVisualSnapshot(snapshot,src),snapshot);
assert.equal(JSON.stringify(src),before,'physics must remain untouched');
for(const key of Object.keys(src))assert.equal(snapshot[key],src[key]);
assert.throws(()=>updateDrivingVisualSnapshot(snapshot,{...src,slipAngleDeg:NaN}),/finite/);
assert.equal(snapshot.slipAngleDeg,13,'invalid frame must not partially mutate snapshot');
assert.throws(()=>updateDrivingVisualSnapshot(snapshot,{...src,driftState:'invalid'}),/driftState/);
const left=createDriftVisualRig();
for(let i=0;i<30;i++)updateDriftVisualRig(left,snapshot,1/60);
assert(left.offsetX<-.08&&left.offsetX>=-.4,'bounded sway');
const right=createDriftVisualRig(),mirrored={...snapshot,driftAngleDeg:-24,slipAngleDeg:-13,driftDirection:-1,lateralVelocity:-.4,yawDeg:-31};
for(let i=0;i<30;i++)updateDriftVisualRig(right,mirrored,1/60);
assert(Math.abs(left.offsetX+right.offsetX)<1e-9,'left/right symmetry');
const frozen=left.offsetX;updateDriftVisualRig(left,snapshot,0);
assert.equal(left.offsetX,frozen,'pause freezes animation');
const recovery={...snapshot,driftState:'recover',isDrifting:true,driftAngleDeg:0,slipAngleDeg:0,lateralVelocity:0};
for(let i=0;i<50;i++)updateDriftVisualRig(left,recovery,1/60);
assert(Math.abs(left.offsetX)<.001,'recover centres smoothly');
resetDriftVisualRig(left);
assert.equal(left.offsetX,0);assert.equal(left.cameraX,0);
assert.throws(()=>updateDriftVisualRig(left,recovery,-.1),/nonnegative/);
console.log('V56.1 drift visual snapshot, symmetry, pause and recovery passed');
