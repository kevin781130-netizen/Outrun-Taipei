'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const files = ['VehiclePoseBridge.cjs', 'Vehicle3D.cjs', 'HybridOverlay.cjs', 'DrivingVisualSnapshot.cjs', 'DriftVisualRig.cjs', 'DrivingEffects.cjs', 'ScenicVisibility.cjs', 'TaipeiLandmarks.cjs', 'RaceEnvironment.cjs', 'RaceWayfinding.cjs', 'CrashChase.cjs', 'RouteGeography.cjs', 'Full3DScene.cjs'];
function bundle() {
  const source = files.map(name => {
    const code = fs.readFileSync(path.join(root, 'src/rendering', name), 'utf8');
    return `  ${JSON.stringify('./' + name)}: function(require, module) {\n${code}\n  }`;
  }).concat('  "../../data/world-v59/scene-profiles.json": function(require, module) {module.exports = '+fs.readFileSync(path.join(root,'data/world-v59/scene-profiles.json'),'utf8')+';}').join(',\n');
  return [
    '/* V55 offline hybrid renderer; generated by tools/build-hybrid.cjs. */',
    '(function(global){',
    `const modules = {\n${source}\n};`,
    'const cache = Object.create(null);',
    'function load(id) {',
    ' if (!Object.prototype.hasOwnProperty.call(modules, id)) throw new Error("Unknown V55 module: " + id);',
    ' if (!cache[id]) { const module = {exports:{}}; cache[id] = module; modules[id](load, module); }',
    ' return cache[id].exports;',
    '}',
    "global.TaipeiHybrid = Object.assign({}, load('./HybridOverlay.cjs'), load('./Full3DScene.cjs'));",
    '})(window);',
    ''
  ].join('\n');
}

const destination = path.join(root, 'assets/hybrid-renderer.js');
const expected = bundle();
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== expected) {
    console.error('Outdated V55 bundle. Run node tools/build-hybrid.cjs');
    process.exitCode = 1;
  } else console.log('V55 bundle is current');
} else {
  fs.mkdirSync(path.dirname(destination), {recursive:true});
  fs.writeFileSync(destination, expected);
  console.log('Created assets/hybrid-renderer.js');
}
